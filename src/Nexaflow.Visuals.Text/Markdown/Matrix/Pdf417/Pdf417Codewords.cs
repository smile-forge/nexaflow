/// <summary>
/// The PDF417 symbol-character table: which bar-and-space pattern stands for each of the 929
/// codewords, in each of the three clusters a row can be drawn in.
///
/// <para>
/// This is data, not an algorithm, and it cannot be derived. Every legal character is 17 modules of
/// four bars and four spaces each one to six wide, but that description admits 1,484 characters in
/// cluster 0 where the standard uses 929, and the ones it picks are not the first, the last, or any
/// ordering of them — so the table is the table. It is checked on the way in rather than trusted:
/// <c>Pdf417EncoderTests</c> asserts every entry really is 17 modules, eight elements of width one to
/// six, in the cluster it is filed under, and <c>Pdf417ReferenceImageTests</c> decodes symbols made by
/// two other generators straight out of it.
/// </para>
/// <para>
/// Fifteen bits each, because a symbol character always begins with a bar and ends with a space: the
