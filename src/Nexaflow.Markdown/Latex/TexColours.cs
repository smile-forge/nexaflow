    /// <summary>The colour written, or null where it names none.</summary>
    public static HexColor? Read(string written)
    {
        var name = written.Trim();

        if (!name.StartsWith('#')) return Named.TryGetValue(name, out var named) ? named : null;

        var hex = name[1..];
        if (hex.Length is not (3 or 4 or 6 or 8) || !hex.All(char.IsAsciiHexDigit)) return null;

        // #RGB and #ARGB are each digit twice over.
        if (hex.Length is 3 or 4) hex = string.Concat(hex.Select(digit => new string(digit, 2)));
        if (hex.Length == 6) hex = "FF" + hex;

        byte Component(int at) => byte.Parse(hex.AsSpan(at * 2, 2), NumberStyles.HexNumber, CultureInfo.InvariantCulture);

        return new HexColor(Component(0), Component(1), Component(2), Component(3));
    }

